const SAFE_TABLES = {
  users: 1,
  sessions: 1,
  email_tokens: 1,
  ledger: 1,
  cashouts: 1,
  streaks: 1,
  daily_goals: 1,
  offer_progress: 1,
  admin_sessions: 1,
  oauth_states: 1
};

async function columnInfo(db, table) {
  if (!SAFE_TABLES[table]) throw new Error('unknown table');
  if (db.dialect === 'pg') {
    return db.all(
      `SELECT column_name AS name, is_nullable
       FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = ?`,
      [table]
    );
  }
  return db.all('PRAGMA table_info(' + table + ')');
}

async function addColumnIfMissing(db, table, name, typ) {
  const cols = await columnInfo(db, table);
  if (cols.some((c) => c.name === name)) return;
  await db.exec('ALTER TABLE ' + table + ' ADD COLUMN ' + name + ' ' + typ);
}

async function sqliteNeedsUserRebuild(db) {
  if (db.dialect !== 'sqlite') return false;
  const cols = await columnInfo(db, 'users');
  if (!cols.length) return false;
  const device = cols.find((c) => c.name === 'device_id');
  const token = cols.find((c) => c.name === 'token');
  // sql.js/SQLite: notnull is 1 when the column is NOT NULL
  if (device && Number(device.notnull) === 1) return true;
  if (token && Number(token.notnull) === 1) return true;
  return false;
}

async function rebuildSqliteUsers(db) {
  await db.exec(`
    CREATE TABLE IF NOT EXISTS users_new (
      id INTEGER PRIMARY KEY,
      public_id TEXT UNIQUE NOT NULL,
      email TEXT UNIQUE,
      password_hash TEXT,
      email_verified_at TEXT,
      agreed_terms_at TEXT,
      age_confirmed INTEGER NOT NULL DEFAULT 0,
      device_fingerprint TEXT,
      device_note TEXT,
      device_id TEXT,
      google_id TEXT UNIQUE,
      apple_id TEXT UNIQUE,
      created_at TEXT NOT NULL,
      first_cashout_at TEXT,
      last_seen_at TEXT
    );
  `);
  const cols = await columnInfo(db, 'users');
  const names = new Set(cols.map((c) => c.name));
  const copy = ['id', 'public_id', 'device_id', 'created_at', 'first_cashout_at', 'last_seen_at']
    .filter((n) => names.has(n));
  await db.exec(
    'INSERT INTO users_new (' + copy.join(',') + ') SELECT ' + copy.join(',') + ' FROM users'
  );
  await db.exec('DROP TABLE users');
  await db.exec('ALTER TABLE users_new RENAME TO users');
  await db.exec('CREATE INDEX IF NOT EXISTS idx_users_email ON users(email)');
}

async function migrate(db) {
  await db.exec(schemaSql(db.dialect));
  if (await sqliteNeedsUserRebuild(db)) {
    await rebuildSqliteUsers(db);
  }
  const extras = [
    ['users', 'email', 'TEXT'],
    ['users', 'password_hash', 'TEXT'],
    ['users', 'email_verified_at', 'TEXT'],
    ['users', 'agreed_terms_at', 'TEXT'],
    ['users', 'age_confirmed', 'INTEGER DEFAULT 0'],
    ['users', 'device_fingerprint', 'TEXT'],
    ['users', 'device_note', 'TEXT'],
    ['users', 'google_id', 'TEXT'],
    ['users', 'apple_id', 'TEXT'],
    ['cashouts', 'payout_provider', 'TEXT'],
    ['cashouts', 'payout_mode', 'TEXT'],
    ['cashouts', 'payout_ref', 'TEXT'],
    ['cashouts', 'payout_error', 'TEXT']
  ];
  for (const [table, name, typ] of extras) {
    await addColumnIfMissing(db, table, name, typ);
  }
  await db.exec('CREATE INDEX IF NOT EXISTS idx_users_email ON users(email)');
  await db.exec('CREATE UNIQUE INDEX IF NOT EXISTS idx_users_google_id ON users(google_id)');
  await db.exec('CREATE UNIQUE INDEX IF NOT EXISTS idx_users_apple_id ON users(apple_id)');
}

function wrapSqlite(db, persistPath) {
  let saveTimer = null;
  let dirty = false;

  function saveNow() {
    if (!persistPath) return;
    const data = db.export();
    fs.mkdirSync(path.dirname(persistPath), { recursive: true });
    fs.writeFileSync(persistPath, Buffer.from(data));
    dirty = false;
  }

  function saveSoon() {
    if (!persistPath) return;
    dirty = true;
    if (saveTimer) return;
    saveTimer = setTimeout(() => {
      saveTimer = null;
      if (dirty) saveNow();
    }, 40);
  }

  function bindParams(stmt, params) {
    if (params == null) return;
    stmt.bind(params);
  }

  async function run(sql, params) {
    const stmt = db.prepare(sql);
    try {
      bindParams(stmt, params);
      stmt.step();
    } finally {
      stmt.free();
    }
    saveSoon();
    const rid = db.exec('SELECT last_insert_rowid() AS id');
    const changes = db.getRowsModified();
    const lastId = rid && rid[0] && rid[0].values[0] ? rid[0].values[0][0] : 0;
    return { lastInsertRowid: lastId, changes };
  }

  async function get(sql, params) {
    const stmt = db.prepare(sql);
    try {
      bindParams(stmt, params);
      if (!stmt.step()) return undefined;
      return stmt.getAsObject();
    } finally {
      stmt.free();
    }
  }

  async function all(sql, params) {
    const stmt = db.prepare(sql);
    const rows = [];
    try {
      bindParams(stmt, params);
      while (stmt.step()) rows.push(stmt.getAsObject());
      return rows;
    } finally {
      stmt.free();
    }
  }

  async function exec(sql) {
    db.exec(sql);
    saveSoon();
  }

  async function close() {
    if (saveTimer) {
      clearTimeout(saveTimer);
      saveTimer = null;
    }
    saveNow();
    db.close();
  }

  return {
    dialect: 'sqlite',
    run, get, all, exec, saveNow, saveSoon, close,
    raw: db,
    persistPath
  };
}

const TABLES_WITH_ID = {
  users: 1,
  email_tokens: 1,
  ledger: 1,
  cashouts: 1,
  daily_goals: 1
};

function insertTable(sql) {
  const m = String(sql).match(/^\s*INSERT\s+INTO\s+([a-zA-Z_][a-zA-Z0-9_]*)/i);
  return m ? m[1].toLowerCase() : null;
}

function wrapPostgres(pool) {
  async function query(sql, params) {
    const text = convertPlaceholders(sql);
    return pool.query(text, params || []);
  }

  async function run(sql, params) {
    const table = insertTable(sql);
    if (table && TABLES_WITH_ID[table] && !/returning\s+/i.test(sql)) {
      const r = await query(sql + ' RETURNING id', params);
      const id = r.rows[0] && r.rows[0].id;
      return { lastInsertRowid: id, changes: r.rowCount };
    }
    const r = await query(sql, params);
    return { lastInsertRowid: 0, changes: r.rowCount };
  }

  async function get(sql, params) {
    const r = await query(sql, params);
    return r.rows[0];
  }

  async function all(sql, params) {
    const r = await query(sql, params);
    return r.rows;
  }

  async function exec(sql) {
    await pool.query(sql);
  }

  async function close() {
    await pool.end();
  }

  return {
    dialect: 'pg',
    run, get, all, exec, close,
    saveNow() {},
    saveSoon() {},
    raw: pool,
    persistPath: null
  };
}

function postgresSsl(url) {
  const s = String(url);
  if (/sslmode=disable/i.test(s)) return false;
  if (/localhost|127\.0\.0\.1/i.test(s)) return false;
  if (/\.internal(?::|\/|$)/i.test(s) && !/sslmode=/i.test(s)) return false;
  return { rejectUnauthorized: false };
}

async function openSqlite(opts) {
  const wasmDir = path.dirname(require.resolve('sql.js/dist/sql-wasm.js'));
  const SQL = await initSqlJs({ locateFile: (f) => path.join(wasmDir, f) });
  const persistPath = opts.memory ? null : opts.path;
  let db;
  if (persistPath && fs.existsSync(persistPath)) {
    db = new SQL.Database(fs.readFileSync(persistPath));
  } else {
    db = new SQL.Database();
  }
  const wrapped = wrapSqlite(db, persistPath);
  await migrate(wrapped);
  wrapped.saveNow();
  return wrapped;
}

async function openPostgres(url) {
  const { Pool } = require('pg');
  const pool = new Pool({
    connectionString: url,
    max: 5,
    ssl: postgresSsl(url),
    connectionTimeoutMillis: 8000
  });
  // Fail fast if the URL is wrong, so the caller can fall back.
  await pool.query('SELECT 1');
  const wrapped = wrapPostgres(pool);
  await migrate(wrapped);
  return wrapped;
}

/**
 * Open the database. Uses Postgres when DATABASE_URL (or opts.databaseUrl)
 * is a real postgres:// / postgresql:// URL and the connection works.
 * Otherwise falls back to sql.js. A memory:true or forceSqlite option
 * always uses sql.js (for tests).
 *
 * Never logs the connection URL itself.
 */
async function openDb(opts) {
  opts = opts || {};
  let url = opts.databaseUrl;
  if (opts.memory || opts.forceSqlite) {
    return openSqlite(opts);
  }
  if (url === undefined) url = process.env.DATABASE_URL;
  if (url != null && String(url).trim() !== '') {
    const trimmed = String(url).trim();
    if (!isPostgresUrl(trimmed)) {
      console.warn(
        'DATABASE_URL is set but it is not a postgres:// or postgresql:// URL. Falling back to the local sql.js database so the app can still start.'
      );
    } else {
      try {
        const db = await openPostgres(trimmed);
        console.log('Database: Postgres');
        return db;
      } catch (e) {
        const msg = (e && e.message) ? e.message : String(e);
        console.warn(
          'Could not connect to Postgres (' + msg + '). Falling back to the local sql.js database so the app can still start.'
        );
      }
    }
  }
  const db = await openSqlite(opts);
  console.log('Database: sql.js (SQLite)');
  return db;
}

